import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const sources = [
    ['cashback', 'Кэшбек', 'Arkadiy (Cashback) Puzirev'],
    ['epstein', 'Доктор Эпштейн', 'Dr. Albert Epstein'],
    ['archiver', 'Архиватор', 'Egor (Archiver) Papochkin'],
    ['gazelov', 'Газель Бизнес-Класс', 'Maksim Gazelov'],
    ['katalonets', 'Каталонец', 'Robert (Katalonets) Ryzhov'],
    ['ayran', 'Айран', 'Yerlan Smagulovich Baizhanov (Ayran)'],
    ['mafioznik', 'Мафиозник', 'Zubenko Michael Petrovich'],
];

// Leave unchanged files alone so starting the server does not trigger a React rebuild.
const writeIfChanged = async (target, content) => {
    const bytes = Buffer.from(content);
    try {
        if (bytes.equals(await readFile(target))) return;
    } catch (error) {
        if (error.code !== 'ENOENT') throw error;
    }
    await writeFile(target, bytes);
};

const characters = [];
await mkdir(path.join(root, 'public/characters'), { recursive: true });
await mkdir(path.join(root, 'src/shared'), { recursive: true });
for (const [id, title, folder] of sources) {
    const source = path.join(root, 'lore', folder);
    const text = (await readFile(path.join(source, 'Lore.md'), 'utf8')).replace(/\r\n/g, '\n').trim();
    const match = text.match(/^(.+)\n+([\s\S]+)\n+color:\s*(\S+)\s*$/);
    if (!match || !/^(black|red|green|yellow|blue|pink|#[\da-f]{6})$/i.test(match[3])) {
        throw new Error(`Invalid name, lore or color in lore/${folder}/Lore.md`);
    }
    const portrait = await readFile(path.join(source, 'Portrait.png'));
    await writeIfChanged(path.join(root, 'public/characters', `${id}.png`), portrait);
    characters.push({ id, title, name: match[1].trim(), color: match[3], lore: match[2].trim(), portrait: `/characters/${id}.png` });
}
const catalog = `// Generated by npm run characters from lore/. Edit the source Lore.md files.\nexport const CHARACTERS = ${JSON.stringify(characters, null, 4)};\n\nconst charactersById = new Map(CHARACTERS.map(character => [character.id, character]));\nexport const getCharacter = id => charactersById.get(id);\n`;
await writeIfChanged(path.join(root, 'src/shared/characters.js'), catalog);
console.log(`Characters: ${characters.length} portraits and stories synced from lore/.`);
